using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace MiniBus.Generator;

public static class DispatcherSourceBuilder
{
    private delegate void PreHandlePhaseEmitter(
        StringBuilder sb,
        HandlerModel model,
        IPreHandlePhaseInfo phase,
        string indent,
        string taskWrap,
        string taskClose);

    private static readonly IReadOnlyDictionary<System.Type, PreHandlePhaseEmitter> PreHandlePhaseEmitters
        = new Dictionary<System.Type, PreHandlePhaseEmitter>
        {
            [typeof(LoadMethodPhase)] = static (sb, model, phase, indent, taskWrap, taskClose) =>
                EmitLoadPhase(sb, model, (LoadMethodPhase)phase, indent, taskWrap, taskClose),
            [typeof(ValidateMethodPhase)] = static (sb, model, phase, indent, taskWrap, taskClose) =>
                EmitValidatePhase(sb, model, (ValidateMethodPhase)phase, indent, taskWrap, taskClose)
        };

    public static string Build(HandlerModel model)
    {
        var sb = new StringBuilder();
        var phases = model.Phases;
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        // ── Dispatcher class ─────────────────────────────────────────────────
        var inNs = model.Namespace is not null;
        var i = inNs ? "    " : "";     // indent when inside a namespace block

        if (inNs) { sb.AppendLine($"namespace {model.Namespace}"); sb.AppendLine("{"); }

        sb.AppendLine($"{i}public class {model.ClassName}Dispatcher");
        sb.AppendLine($"{i}    : global::MiniBus.IDispatcher<");
        sb.AppendLine($"{i}        {model.FullRequestType},");
        sb.AppendLine($"{i}        {model.FullResponseType}>");
        sb.AppendLine($"{i}{{");
        sb.AppendLine($"{i}    private readonly {model.FullClassName} _handler;");
        sb.AppendLine();
        sb.AppendLine($"{i}    public {model.ClassName}Dispatcher({model.FullClassName} handler)");
        sb.AppendLine($"{i}    {{");
        sb.AppendLine($"{i}        _handler = handler;");
        sb.AppendLine($"{i}    }}");
        sb.AppendLine();
        sb.AppendLine($"{i}    public string HandlerName => nameof({model.FullClassName});");
        sb.AppendLine();
        var asyncKeyword = model.IsAnyAsync ? "async " : "";
        var taskWrap  = model.IsAnyAsync ? "" : "global::System.Threading.Tasks.Task.FromResult(";
        var taskClose = model.IsAnyAsync ? "" : ")";
        sb.AppendLine($"{i}    public {asyncKeyword}global::System.Threading.Tasks.Task<");
        sb.AppendLine($"{i}        global::MiniBus.Result<{model.FullResponseType}>>");
        sb.AppendLine($"{i}        Handle({model.FullRequestType} request)");
        sb.AppendLine($"{i}    {{");

        var preHandlePhases = phases.GetPreHandlePhases()
            .OrderBy(static p => p.Order)
            .ThenBy(static p => p.TieBreak);
        foreach (var preHandlePhase in preHandlePhases)
        {
            if (PreHandlePhaseEmitters.TryGetValue(preHandlePhase.GetType(), out var emitter))
            {
                emitter(sb, model, preHandlePhase, i, taskWrap, taskClose);
            }
        }

        // ── Handle phase ──────────────────────────────────────────────────────
        var handle = phases.GetRequiredPhase<HandleMethodPhase>();
        var handleAwait = handle.IsAsync ? "await " : "";
        sb.AppendLine($"{i}        var response = {handleAwait}_handler.Handle({handle.CallArgs});");
        sb.AppendLine($"{i}        return {taskWrap}global::MiniBus.Result<{model.FullResponseType}>.Success(response){taskClose};");
        sb.AppendLine($"{i}    }}");
        sb.AppendLine($"{i}}}");

        if (inNs) sb.AppendLine("}");

        return sb.ToString();
    }

    private static void EmitLoadPhase(
        StringBuilder sb,
        HandlerModel model,
        LoadMethodPhase load,
        string indent,
        string taskWrap,
        string taskClose)
    {
        var awaitPrefix = load.IsAsync ? "await " : "";
        var loadCallArgs = load.CallArgs;
        if (load.IsTuple)
        {
            var varNames = string.Join(", ", load.Elements.Select(e => e.LocalName));
            sb.AppendLine($"{indent}        var ({varNames}) = {awaitPrefix}_handler.Load({loadCallArgs});");
        }
        else
        {
            sb.AppendLine($"{indent}        var {load.Elements[0].LocalName} = {awaitPrefix}_handler.Load({loadCallArgs});");
        }

        var nullableElements = load.Elements.Where(e => e.IsNullable).ToArray();
        foreach (var element in nullableElements)
        {
            var notFoundArg = element.NotFoundMessage is not null ? $"\"{element.NotFoundMessage}\"" : "";
            sb.AppendLine($"{indent}        if ({element.LocalName} is not {{ }} {element.NonNullLocalName})");
            sb.AppendLine($"{indent}            return {taskWrap}global::MiniBus.Result<{model.FullResponseType}>.NotFound({notFoundArg}){taskClose};");
        }

        sb.AppendLine();
    }

    private static void EmitValidatePhase(
        StringBuilder sb,
        HandlerModel model,
        ValidateMethodPhase validate,
        string indent,
        string taskWrap,
        string taskClose)
    {
        var validateAwait = validate.IsAsync ? "await " : "";
        sb.AppendLine($"{indent}        var validationResult = {validateAwait}_handler.Validate({validate.CallArgs});");
        sb.AppendLine($"{indent}        if (!validationResult.IsValid())");
        sb.AppendLine($"{indent}            return {taskWrap}global::MiniBus.Result<{model.FullResponseType}>.Invalid(validationResult){taskClose};");
        sb.AppendLine();
    }
}
